/// Boolean operation type for 3D extrusion features.
enum AssemblyExtrudeOperation {
  newBody,
  join,
  cut,
  intersect;

  String get label {
    switch (this) {
      case AssemblyExtrudeOperation.newBody:
        return 'New Body';
      case AssemblyExtrudeOperation.join:
        return 'Join';
      case AssemblyExtrudeOperation.cut:
        return 'Cut';
      case AssemblyExtrudeOperation.intersect:
        return 'Intersect';
    }
  }

  IconData get icon {
    switch (this) {
      case AssemblyExtrudeOperation.newBody:
        return Icons.add_box_rounded;
      case AssemblyExtrudeOperation.join:
        return Icons.merge_type_rounded;
      case AssemblyExtrudeOperation.cut:
        return Icons.content_cut_rounded;
      case AssemblyExtrudeOperation.intersect:
        return Icons.join_inner_rounded;
    }
  }

  Color get color {
    switch (this) {
      case AssemblyExtrudeOperation.newBody:
        return const Color(0xFF38BDF8);
      case AssemblyExtrudeOperation.join:
        return const Color(0xFF10B981);
      case AssemblyExtrudeOperation.cut:
        return const Color(0xFFEF4444);
      case AssemblyExtrudeOperation.intersect:
        return const Color(0xFFF59E0B);
    }
  }
}

/// Extrusion direction / extent mode.
enum AssemblyExtrudeDirection {
  oneSide,
  symmetric,
  twoSide;

  String get label {
    switch (this) {
      case AssemblyExtrudeDirection.oneSide:
        return 'One Side';
      case AssemblyExtrudeDirection.symmetric:
        return 'Symmetric';
      case AssemblyExtrudeDirection.twoSide:
        return 'Two Sides';
    }
  }
}

/// Parametric parameters defining a 3D extrusion feature.
class AssemblyExtrudeParams {
  final double distanceMm;
  final double distanceSide2Mm;
  final double taperAngleDeg;
  final AssemblyExtrudeDirection direction;
  final AssemblyExtrudeOperation operation;
  final List<String> profileEntityIds;

  const AssemblyExtrudeParams({
    this.distanceMm = 25.0,
    this.distanceSide2Mm = 0.0,
    this.taperAngleDeg = 0.0,
    this.direction = AssemblyExtrudeDirection.oneSide,
    this.operation = AssemblyExtrudeOperation.newBody,
    this.profileEntityIds = const [],
  });

  AssemblyExtrudeParams copyWith({
    double? distanceMm,
    double? distanceSide2Mm,
    double? taperAngleDeg,
    AssemblyExtrudeDirection? direction,
    AssemblyExtrudeOperation? operation,
    List<String>? profileEntityIds,
  }) {
    return AssemblyExtrudeParams(
      distanceMm: distanceMm ?? this.distanceMm,
      distanceSide2Mm: distanceSide2Mm ?? this.distanceSide2Mm,
      taperAngleDeg: taperAngleDeg ?? this.taperAngleDeg,
      direction: direction ?? this.direction,
      operation: operation ?? this.operation,
      profileEntityIds: profileEntityIds ?? this.profileEntityIds,
    );
  }
}

/// Resulting 3D solid geometry generated by extrusion.
class ExtrudedSolidMesh {
  final List<CadFoldedPolygon3D> polygons;
  final double volumeMm3;
  final CadPoint3D centroid;
  final double boundWidth;
  final double boundLength;
  final double boundHeight;

  const ExtrudedSolidMesh({
    required this.polygons,
    required this.volumeMm3,
    required this.centroid,
    required this.boundWidth,
    required this.boundLength,
    required this.boundHeight,
  });

  bool get isEmpty => polygons.isEmpty;
}

/// Result of executing an extrusion feature on the document.
class AssemblyExtrudeResult {
  final bool isSuccess;
  final String message;
  final ExtrudedSolidMesh? mesh;
  final AssemblyPart? createdPart;
  final AssemblySketchFeature? cutFeature;

  const AssemblyExtrudeResult({
    required this.isSuccess,
    required this.message,
    this.mesh,
    this.createdPart,
    this.cutFeature,
  });
}

/// Mathematical core engine for 3D extrusion, solid face construction, and boolean operations.
class AssemblyExtrudeEngine {
  /// Generates watertight 3D solid mesh polygons by extruding 2D [profilePoints] from [plane].
  static ExtrudedSolidMesh generateExtrudedSolid({
    required CADSketchPlane plane,
    required List<Offset> profilePoints,
    required AssemblyExtrudeParams params,
    Color color = const Color(0xFF64748B),
  }) {
    if (profilePoints.length < 3) {
      return const ExtrudedSolidMesh(
        polygons: [],
        volumeMm3: 0.0,
        centroid: CadPoint3D(0.0, 0.0, 0.0),
        boundWidth: 0.0,
        boundLength: 0.0,
        boundHeight: 0.0,
      );
    }

    // Clean vertices: remove duplicate closing vertex if present
    final loop = List<Offset>.from(profilePoints);
    if ((loop.first - loop.last).distance < 0.001) {
      loop.removeLast();
    }
    if (loop.length < 3) {
      return const ExtrudedSolidMesh(
        polygons: [],
        volumeMm3: 0.0,
        centroid: CadPoint3D(0.0, 0.0, 0.0),
        boundWidth: 0.0,
        boundLength: 0.0,
        boundHeight: 0.0,
      );
    }

    // 1. Determine extrusion heights along plane normal
    double d0 = 0.0;
    double d1 = params.distanceMm;

    switch (params.direction) {
      case AssemblyExtrudeDirection.oneSide:
        d0 = 0.0;
        d1 = params.distanceMm;
        break;
      case AssemblyExtrudeDirection.symmetric:
        final half = params.distanceMm.abs();
        d0 = -half;
        d1 = half;
        break;
      case AssemblyExtrudeDirection.twoSide:
        d0 = -params.distanceSide2Mm.abs();
        d1 = params.distanceMm;
        break;
    }

    // 2. Compute 2D centroid and area via Shoelace formula
    double area2d = 0.0;
    double cx2d = 0.0;
    double cy2d = 0.0;
    final n = loop.length;
    for (int i = 0; i < n; i++) {
      final j = (i + 1) % n;
      final cross = loop[i].dx * loop[j].dy - loop[j].dx * loop[i].dy;
      area2d += cross;
      cx2d += (loop[i].dx + loop[j].dx) * cross;
      cy2d += (loop[i].dy + loop[j].dy) * cross;
    }
    area2d = area2d / 2.0;
    if (area2d.abs() > 1e-5) {
      cx2d = cx2d / (6.0 * area2d);
      cy2d = cy2d / (6.0 * area2d);
    } else {
      cx2d = loop.map((p) => p.dx).reduce((a, b) => a + b) / n;
      cy2d = loop.map((p) => p.dy).reduce((a, b) => a + b) / n;
    }
    final centroid2d = Offset(cx2d, cy2d);

    // 3. Apply taper draft angle scaling if specified
    final taperRad = params.taperAngleDeg * math.pi / 180.0;
    final hasTaper = taperRad.abs() > 1e-4;

    Offset scalePoint(Offset pt, double heightOffset) {
      if (!hasTaper) return pt;
      final scale = (1.0 + math.tan(taperRad) * (heightOffset / 100.0)).clamp(0.05, 5.0);
      return centroid2d + (pt - centroid2d) * scale;
    }

    final bot2d = loop.map((pt) => scalePoint(pt, d0)).toList();
    final top2d = loop.map((pt) => scalePoint(pt, d1)).toList();

    // 4. Map 2D plane points into 3D World coordinates
    final origin = plane.origin;
    final xAxis = plane.xAxis.normalized();
    final yAxis = plane.yAxis.normalized();
    final normal = plane.normal.normalized();

    CadPoint3D to3D(Offset pt2d, double heightDist) {
      final px = origin.x + xAxis.x * pt2d.dx + yAxis.x * pt2d.dy + normal.x * heightDist;
      final py = origin.y + xAxis.y * pt2d.dx + yAxis.y * pt2d.dy + normal.y * heightDist;
      final pz = origin.z + xAxis.z * pt2d.dx + yAxis.z * pt2d.dy + normal.z * heightDist;
      return CadPoint3D(px, py, pz);
    }

    final bot3d = bot2d.map((p) => to3D(p, d0)).toList();
    final top3d = top2d.map((p) => to3D(p, d1)).toList();

    final polygons = <CadFoldedPolygon3D>[];

    // 5. Build Top Cap (Ear-clipping triangulation)
    var topIndices = CADTessellator.tessellatePolygon(top2d);
    if (topIndices.isEmpty) {
      topIndices = CADTessellator.tessellatePolygon(top2d.reversed.toList());
    }
    final topNorm = CadPoint3D(normal.x, normal.y, normal.z);
    for (int t = 0; t + 2 < topIndices.length; t += 3) {
      final i0 = topIndices[t];
      final i1 = topIndices[t + 1];
      final i2 = topIndices[t + 2];
      polygons.add(
        CadFoldedPolygon3D(
          faceId: 'extrude_top_cap_$t',
          vertices: [top3d[i0], top3d[i1], top3d[i2]],
          normal: topNorm,
          color: color,
        ),
      );
    }

    // 6. Build Bottom Cap (Reversed winding, normal pointing -normal)
    var botIndices = CADTessellator.tessellatePolygon(bot2d.reversed.toList());
    if (botIndices.isEmpty) {
      botIndices = CADTessellator.tessellatePolygon(bot2d);
    }
    final botNorm = CadPoint3D(-normal.x, -normal.y, -normal.z);
    for (int t = 0; t + 2 < botIndices.length; t += 3) {
      final i0 = botIndices[t];
      final i1 = botIndices[t + 1];
      final i2 = botIndices[t + 2];
      polygons.add(
        CadFoldedPolygon3D(
          faceId: 'extrude_bot_cap_$t',
          vertices: [bot3d[i0], bot3d[i1], bot3d[i2]],
          normal: botNorm,
          color: color,
        ),
      );
    }

    // 7. Build Side Wall Quads (2 Triangles per edge)
    for (int i = 0; i < n; i++) {
      final j = (i + 1) % n;
      final pBot1 = bot3d[i];
      final pBot2 = bot3d[j];
      final pTop2 = top3d[j];
      final pTop1 = top3d[i];

      // Side normal calculation
      final vEdge = vm_math.Vector3(pBot2.x - pBot1.x, pBot2.y - pBot1.y, pBot2.z - pBot1.z);
      final vUp = vm_math.Vector3(pTop1.x - pBot1.x, pTop1.y - pBot1.y, pTop1.z - pBot1.z);
      final sideNormalVec = vEdge.cross(vUp).normalized();
      final sideNorm = CadPoint3D(sideNormalVec.x, sideNormalVec.y, sideNormalVec.z);

      // Triangle 1: pBot1 -> pBot2 -> pTop2
      polygons.add(
        CadFoldedPolygon3D(
          faceId: 'extrude_wall_${i}_a',
          vertices: [pBot1, pBot2, pTop2],
          normal: sideNorm,
          color: color,
        ),
      );

      // Triangle 2: pBot1 -> pTop2 -> pTop1
      polygons.add(
        CadFoldedPolygon3D(
          faceId: 'extrude_wall_${i}_b',
          vertices: [pBot1, pTop2, pTop1],
          normal: sideNorm,
          color: color,
        ),
      );
    }

    // 8. Compute Bounding Box, Centroid, and Volume
    double minX = double.infinity, maxX = -double.infinity;
    double minY = double.infinity, maxY = -double.infinity;
    double minZ = double.infinity, maxZ = -double.infinity;
    double sumX = 0, sumY = 0, sumZ = 0;
    int totalVerts = 0;

    for (final poly in polygons) {
      for (final v in poly.vertices) {
        if (v.x < minX) minX = v.x;
        if (v.x > maxX) maxX = v.x;
        if (v.y < minY) minY = v.y;
        if (v.y > maxY) maxY = v.y;
        if (v.z < minZ) minZ = v.z;
        if (v.z > maxZ) maxZ = v.z;
        sumX += v.x;
        sumY += v.y;
        sumZ += v.z;
        totalVerts++;
      }
    }

    final totalHeight = (d1 - d0).abs();
    final volume = area2d.abs() * totalHeight;
    final centroid3d = totalVerts > 0
        ? CadPoint3D(sumX / totalVerts, sumY / totalVerts, sumZ / totalVerts)
        : CadPoint3D(origin.x, origin.y, origin.z);

    return ExtrudedSolidMesh(
      polygons: polygons,
      volumeMm3: volume,
      centroid: centroid3d,
      boundWidth: (maxX - minX).abs(),
      boundLength: (maxY - minY).abs(),
      boundHeight: (maxZ - minZ).abs(),
    );
  }

  /// Executes extrusion and commits boolean solid operation (New Body, Join, Cut, Intersect) into the document.
  static AssemblyExtrudeResult executeExtrusion({
    required AssemblyDocument doc,
    required CADSketchPlane plane,
    required List<Offset> profilePoints,
    required AssemblyExtrudeParams params,
    AssemblyPart? targetPart,
    Color partColor = const Color(0xFF64748B),
  }) {
    final solidMesh = generateExtrudedSolid(
      plane: plane,
      profilePoints: profilePoints,
      params: params,
      color: partColor,
    );

    if (solidMesh.isEmpty) {
      return const AssemblyExtrudeResult(
        isSuccess: false,
        message: 'Unable to extrude solid: invalid or self-intersecting profile loop.',
      );
    }

    switch (params.operation) {
      case AssemblyExtrudeOperation.newBody:
        final nextNum = doc.parts.where((p) => p.type == AssemblyPartType.customExtrusion).length + 1;
        final newPart = AssemblyPart(
          id: 'extruded_body_${DateTime.now().millisecondsSinceEpoch}',
          name: 'Extruded Body $nextNum',
          type: AssemblyPartType.customExtrusion,
          position: const CadPoint3D(0.0, 0.0, 0.0),
          rotationDeg: const CadPoint3D(0.0, 0.0, 0.0),
          length: solidMesh.boundWidth > 0 ? solidMesh.boundWidth : 50.0,
          height: solidMesh.boundLength > 0 ? solidMesh.boundLength : 50.0,
          color: partColor,
          customPolygons: solidMesh.polygons,
        );
        doc.parts.add(newPart);
        doc.selectedPartId = newPart.id;
        return AssemblyExtrudeResult(
          isSuccess: true,
          message: 'Created New Body "${newPart.name}" (${params.distanceMm.toStringAsFixed(1)} mm)',
          mesh: solidMesh,
          createdPart: newPart,
        );

      case AssemblyExtrudeOperation.join:
        final target = targetPart ?? (doc.parts.isNotEmpty ? doc.parts.first : null);
        if (target == null) {
          return const AssemblyExtrudeResult(
            isSuccess: false,
            message: 'Join failed: No target part exists to join with.',
          );
        }
        target.customPolygons ??= target.build3DMesh().polygons;
        target.customPolygons!.addAll(solidMesh.polygons);
        return AssemblyExtrudeResult(
          isSuccess: true,
          message: 'Joined extrusion into "${target.name}"',
          mesh: solidMesh,
          createdPart: target,
        );

      case AssemblyExtrudeOperation.cut:
        final target = targetPart ?? (doc.parts.isNotEmpty ? doc.parts.first : null);
        if (target == null) {
          return const AssemblyExtrudeResult(
            isSuccess: false,
            message: 'Cut failed: No target part exists to subtract from.',
          );
        }
        // Create custom sketch void cut feature on target
        final cx = profilePoints.map((p) => p.dx).reduce((a, b) => a + b) / profilePoints.length;
        final cy = profilePoints.map((p) => p.dy).reduce((a, b) => a + b) / profilePoints.length;
        final worldVec = plane.toWorld(Offset(cx, cy));
        final local3D = target.worldToLocal(CadPoint3D(worldVec.x, worldVec.y, worldVec.z));
        final faceId = plane.targetFaceId ?? 'web';
        final partLocalCenter = (faceId.contains('flange_top') || faceId.contains('flange_bot') || faceId.contains('bar_top'))
            ? CadPoint2D(local3D.x, local3D.y.abs())
            : CadPoint2D(local3D.x, local3D.z);

        final cutFeature = AssemblySketchFeature(
          id: 'cut_${DateTime.now().millisecondsSinceEpoch}',
          featureType: 'extruded_cut',
          localCenter: partLocalCenter,
          widthMm: solidMesh.boundWidth > 0 ? solidMesh.boundWidth : 20.0,
          heightMm: solidMesh.boundLength > 0 ? solidMesh.boundLength : 20.0,
          targetFace: plane.targetFaceId ?? 'web',
          isPassThrough: false,
          isSurfaceImpress: false,
          cutDepthMm: params.distanceMm.abs(),
          customPolygonPoints: profilePoints.map((p) => Offset(p.dx - cx, p.dy - cy)).toList(),
          planeId: plane.id,
        );
        target.sketches.add(cutFeature);
        return AssemblyExtrudeResult(
          isSuccess: true,
          message: 'Cut feature punched into "${target.name}" (${params.distanceMm.toStringAsFixed(1)} mm depth)',
          mesh: solidMesh,
          createdPart: target,
          cutFeature: cutFeature,
        );

      case AssemblyExtrudeOperation.intersect:
        final target = targetPart ?? (doc.parts.isNotEmpty ? doc.parts.first : null);
        if (target == null) {
          return const AssemblyExtrudeResult(
            isSuccess: false,
            message: 'Intersect failed: No target part exists.',
          );
        }
        target.customPolygons = solidMesh.polygons;
        return AssemblyExtrudeResult(
          isSuccess: true,
          message: 'Retained intersection volume on "${target.name}"',
          mesh: solidMesh,
          createdPart: target,
        );
    }
  }
}
